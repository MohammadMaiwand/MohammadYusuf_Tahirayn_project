export function permissionLabels(values: readonly string[]) {
  const output: Record<string, readonly [string, string, string]> = {};
  for (const value of values) {
    const [group, action, scope] = value.split('.');
    output['permission.' + value] = [0, 1, 2].map(
      (index) =>
        `${labels[group!]?.[index] || group}: ${actions[action!]?.[index] || action}${scope ? (index === 0 ? ` (${scope})` : scope === 'own' ? ' (شخصی)' : ' (همه)') : ''}`,
    ) as [string, string, string];
  }
  return output;
}
